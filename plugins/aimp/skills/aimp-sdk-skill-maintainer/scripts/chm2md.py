#!/usr/bin/env python3
"""Convert one decompiled AIMP-en.chm topic page into Markdown.

The AIMP help is generated by a documentation tool with a very regular shape:

  div.content
    span.group_header        -> section heading  ("Description", "Methods", ...)
    table.group              -> the section body
      table.cm_table         -> one documented member (method / property / const)
        tr > th              -> member name
        tr > td[colspan=2]   -> prose
        tr > td.code_param_var + td.code_param_notes  -> key/value row

This module is imported by extract_sdk.py; run it directly to convert a single
file for spot-checking:

    python chm2md.py <topic.html>
"""

from __future__ import annotations

import html
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

WS = re.compile(r'[ \t]+')
BLANKS = re.compile(r'\n{3,}')

# Tags whose content we drop entirely.
SKIP_TAGS = {'script', 'style', 'head'}


class TopicParser(HTMLParser):
    """Streams a topic page into a list of Markdown chunks."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.out: list[str] = []
        self.title = ''
        self._skip = 0
        self._in_title = False
        self._in_content = False
        self._content_depth = 0
        self._pre = 0
        self._pre_buf: list[str] = []
        self._cm = 0
        self._cell: list[str] | None = None
        self._cell_kind = ''
        self._row_cells: list[tuple[str, str]] = []
        self._spans: list[str] = []
        self._tables: list[dict] = []

    # ---------------------------------------------------------------- helpers

    def emit(self, text: str) -> None:
        if self._cell is not None:
            self._cell.append(text)
        else:
            self.out.append(text)

    @staticmethod
    def _classes(attrs) -> set:
        d = dict(attrs)
        return set((d.get('class') or '').split())

    # ------------------------------------------------------------ tag handling

    def handle_starttag(self, tag, attrs):
        cls = self._classes(attrs)

        if tag in SKIP_TAGS:
            self._skip += 1
            return
        if self._skip:
            return

        if tag == 'title':
            self._in_title = True
            return

        if tag == 'div' and 'content' in cls:
            self._in_content = True
            self._content_depth = 1
            return
        if self._in_content and tag == 'div':
            self._content_depth += 1
        if not self._in_content:
            return

        if tag == 'pre':
            self._pre += 1
            self._pre_buf = []
            return
        if self._pre:
            if tag == 'br':
                self._pre_buf.append('\n')
            return

        if tag == 'span':
            # group_header -> section heading; v -> inline code; comment -> "Since vX"
            if 'group_header' in cls:
                kind = 'group_header'
                self.emit('\n\n## ')
            elif 'v' in cls:
                kind = 'code'
                self.emit('`')
            elif 'comment' in cls:
                kind = 'comment'
                self.emit(' _(')
            else:
                kind = 'plain'
            self._spans.append(kind)
            return
        if tag in ('h1', 'h2', 'h3', 'h4'):
            self.emit('\n\n## ')
            return
        if tag == 'table':
            self._tables.append({'cm': 'cm_table' in cls, 'rows': 0})
            if 'cm_table' in cls:
                self._cm += 1
            self.emit('\n')
            return
        if tag == 'tr':
            self._row_cells = []
            return
        if tag in ('td', 'th'):
            self._cell = []
            if tag == 'th':
                self._cell_kind = 'name'
            elif 'code_param_var' in cls:
                self._cell_kind = 'key'
            elif 'code_param_notes' in cls or 'hotkey' in cls:
                self._cell_kind = 'val'
            else:
                self._cell_kind = 'prose'
            return
        if tag == 'br':
            self.emit('\n')
            return
        if tag in ('b', 'strong'):
            self.emit('**')
            return
        if tag == 'li':
            self.emit('\n- ')
            return
        if tag == 'p':
            self.emit('\n\n')
            return

    def handle_endtag(self, tag):
        if tag in SKIP_TAGS:
            self._skip = max(0, self._skip - 1)
            return
        if self._skip:
            return
        if tag == 'title':
            self._in_title = False
            return
        if not self._in_content:
            return

        if tag == 'pre':
            self._pre = max(0, self._pre - 1)
            code = ''.join(self._pre_buf).strip('\n')
            code = '\n'.join(line.rstrip() for line in code.split('\n'))
            if code:
                self.emit('\n\n```\n%s\n```\n\n' % code)
            self._pre_buf = []
            return
        if self._pre:
            return

        if tag == 'div':
            self._content_depth -= 1
            if self._content_depth <= 0:
                self._in_content = False
            return
        if tag == 'span':
            kind = self._spans.pop() if self._spans else 'plain'
            if kind == 'group_header':
                self.emit('\n\n')
            elif kind == 'code':
                self.emit('`')
            elif kind == 'comment':
                self.emit(')_ ')
            return
        if tag in ('h1', 'h2', 'h3', 'h4'):
            self.emit('\n\n')
            return
        if tag == 'table':
            table = self._tables.pop() if self._tables else None
            if table and table['cm']:
                self._cm = max(0, self._cm - 1)
            self.emit('\n')
            return
        if tag in ('td', 'th'):
            text = ''.join(self._cell or [])
            self._cell = None
            self._row_cells.append((self._cell_kind, text))
            return
        if tag == 'tr':
            self._flush_row()
            return
        if tag in ('b', 'strong'):
            self.emit('**')
            return

    def handle_data(self, data):
        if self._in_title:
            self.title += data.strip()
            return
        if self._skip or not self._in_content:
            return
        if self._pre:
            self._pre_buf.append(data)
            return
        self.emit(WS.sub(' ', data.replace('\n', ' ')))

    # ------------------------------------------------------------- row output

    def _flush_row(self) -> None:
        cells = self._row_cells
        self._row_cells = []
        if not cells:
            return
        kinds = [k for k, _ in cells]

        in_cm = bool(self._tables and self._tables[-1]['cm'])

        # In a member table the <th> row is the member name; in a plain table
        # it is a real column header.
        if 'name' in kinds and (in_cm or len(cells) < 2):
            name = clean_inline(' '.join(t.strip() for _, t in cells))
            if name:
                self.out.append('\n\n### %s\n' % name)
            return

        # Signature rows: <dir> <name> <type> <notes>, e.g. "in | Item |
        # IAIMPPlaybackQueueItem | Note 1: ...". Also the 2-column
        # property rows ("Type | Integer") and the Summary table
        # ("Definition: | apiPlayer.pas / apiPlayer.h").
        if kinds[0] in ('key', 'prose') and kinds[-1] == 'val':
            heads = [clean_inline(t) for _, t in cells[:-1]]
            val = clean_block(cells[-1][1]).replace('\n', '\n  ')
            if not any(heads) and not val:
                return
            if len(heads) >= 3:
                direction, name, ptype = heads[0], heads[1], ' '.join(heads[2:])
                line = '- `%s` **%s** — `%s`' % (direction, name, ptype)
                if val:
                    line += '\n  %s' % val
            else:
                key = ' '.join(h for h in heads if h).rstrip(':')
                line = '- **%s:** %s' % (key or '?', val)
            self.out.append('\n' + line)
            return

        # A plain multi-column table (the Windows/Linux comparison in the Linux
        # support topic, for instance) — keep it a table, not run-on prose.
        table = self._tables[-1] if self._tables else None
        if table and not in_cm and len(cells) >= 2:
            cols = [clean_inline(t).replace('|', '\\|') or ' ' for _, t in cells]
            row = '| %s |' % ' | '.join(cols)
            if table['rows'] == 0:
                row += '\n|%s|' % '|'.join(['---'] * len(cols))
            table['rows'] += 1
            self.out.append('\n' + row)
            return

        text = clean_block(' '.join(t for _, t in cells))
        if text:
            self.out.append('\n\n%s\n' % text)


def clean_inline(text: str) -> str:
    text = text.replace('**', '')
    return WS.sub(' ', text.replace('\n', ' ')).strip()


def clean_block(text: str) -> str:
    lines = [WS.sub(' ', ln).strip() for ln in text.split('\n')]
    out: list[str] = []
    for ln in lines:
        if not ln and (not out or not out[-1]):
            continue
        out.append(ln)
    while out and not out[-1]:
        out.pop()
    return '\n'.join(out).strip()


def convert(path: Path) -> tuple:
    """Return (title, markdown_body) for one topic file."""
    raw = path.read_bytes()
    text = ''
    for enc in ('windows-1250', 'windows-1251', 'utf-8', 'latin-1'):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    p = TopicParser()
    p.feed(text)
    body = ''.join(p.out)
    body = html.unescape(body)
    body = '\n'.join(ln.rstrip() for ln in body.split('\n'))
    body = BLANKS.sub('\n\n', body).strip()
    return (p.title or path.stem), body


if __name__ == '__main__':
    t, b = convert(Path(sys.argv[1]))
    print('# %s\n' % t)
    print(b)
